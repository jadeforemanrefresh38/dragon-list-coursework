ALTER TABLE notes ADD COLUMN note_type VARCHAR(10) NOT NULL DEFAULT 'note' CHECK(note_type IN ('note','todo'));
ALTER TABLE notes ADD COLUMN position INTEGER NOT NULL DEFAULT 0;
ALTER TABLE notes ADD COLUMN is_pinned BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE notes ADD COLUMN updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP;
ALTER TABLE notes ADD COLUMN deleted_at TIMESTAMP WITH TIME ZONE;
CREATE INDEX notes_user_status ON notes(user_id,status,is_pinned,position);
CREATE TABLE user_tags (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 name VARCHAR(50) NOT NULL,
 color VARCHAR(7) NOT NULL DEFAULT '#9333ea',
 UNIQUE(user_id,name)
);
CREATE TABLE note_tags (
 note_id BIGINT NOT NULL REFERENCES notes(id) ON DELETE CASCADE,
 tag_id BIGINT NOT NULL REFERENCES user_tags(id) ON DELETE CASCADE,
 PRIMARY KEY(note_id,tag_id)
);
CREATE TABLE todos (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 note_id BIGINT NOT NULL REFERENCES notes(id) ON DELETE CASCADE,
 text VARCHAR(500) NOT NULL,
 done BOOLEAN NOT NULL DEFAULT FALSE,
 position INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE media (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 note_id BIGINT REFERENCES notes(id) ON DELETE CASCADE,
 content_type VARCHAR(40) NOT NULL,
 data BYTEA NOT NULL
);
CREATE TABLE profiles (
 user_id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
 email VARCHAR(254) NOT NULL DEFAULT '',
 bio VARCHAR(300) NOT NULL DEFAULT '',
 avatar_id BIGINT REFERENCES media(id) ON DELETE SET NULL,
 tags_initialized BOOLEAN NOT NULL DEFAULT FALSE
);
