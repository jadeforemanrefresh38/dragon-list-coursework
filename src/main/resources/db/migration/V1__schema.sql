CREATE TABLE users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 login VARCHAR(32) NOT NULL UNIQUE,
 password VARCHAR(100) NOT NULL
);
CREATE TABLE notes (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 title VARCHAR(200) NOT NULL,
 content TEXT NOT NULL,
 tag VARCHAR(16) NOT NULL CHECK(tag IN ('IMPORTANT','IDEAS','STUDY','PERSONAL')),
 created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX notes_user_created ON notes(user_id,created_at DESC,id DESC);
CREATE INDEX notes_user_tag_created ON notes(user_id,tag,created_at DESC,id DESC);
